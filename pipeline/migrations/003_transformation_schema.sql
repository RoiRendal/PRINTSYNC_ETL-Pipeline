-- 003_transformation_schema.sql
--
-- The Transformation stage's output schema, in the pipeline's own database: psync_analytics.
--
-- Eleven tables (doc section 6.1): four dimensions, four facts, the quarantine, and this stage's
-- two metadata tables. Nothing in this file touches PRINTSYNC.
--
-- Apply against the migrated psync_analytics database:
--   python -m psync_extract.db migrate
--
-- Conventions (doc section 6.2):
--   * dimensions carry a generated surrogate key (`branch_key`, `item_key`, `status_key`);
--     `dim_date`'s key is the date itself, because a calendar date has no smaller identifier;
--   * facts carry no surrogate key — their primary key IS their grain, the combination of the
--     dimension keys they reference;
--   * money is numeric(14,2), percentages numeric(6,2), and every moment is timestamptz.
--
-- The CHECK constraints below are a second line of defence, not the first. The document's
-- validation checks (section 7) catch a bad batch and report it; these catch a bug in the
-- transformation before it can store a figure that contradicts itself.

BEGIN;

-- =============================================================================================
-- dim_date                                                    (doc section 6.1, rule M-01)
--
-- Generated for every date a batch touches, including the trailing demand window. The key is the
-- date itself: `date_key = 20261002` alongside `business_date = '2026-10-02'` would be two columns
-- carrying one fact, and the pair could disagree.
-- =============================================================================================
CREATE TABLE dim_date (
    date_key     date     PRIMARY KEY,
    year         smallint NOT NULL,
    quarter      smallint NOT NULL CHECK (quarter BETWEEN 1 AND 4),
    month        smallint NOT NULL CHECK (month BETWEEN 1 AND 12),
    month_name   text     NOT NULL,
    day_of_month smallint NOT NULL CHECK (day_of_month BETWEEN 1 AND 31),
    iso_week     smallint NOT NULL CHECK (iso_week BETWEEN 1 AND 53),
    day_of_week  smallint NOT NULL CHECK (day_of_week BETWEEN 1 AND 7),
    day_name     text     NOT NULL,
    is_weekend   boolean  NOT NULL
);

COMMENT ON COLUMN dim_date.date_key IS
    'The calendar date. day_of_week is 1 = Monday, 7 = Sunday (ISO-8601), not the SQL extract() convention.';

-- =============================================================================================
-- dim_branch                                                  (doc section 6.1, rules M-02, M-06)
--
-- SCD Type 2. A branch attribute that changes (its name, its VAT rate, whether it is still
-- trading) closes the current version and opens a new one, so a fact row from last month still
-- points at the settings that were true last month.
-- =============================================================================================
CREATE TABLE dim_branch (
    branch_key      bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    branch_id       uuid         NOT NULL,
    code            text         NOT NULL,
    name            text         NOT NULL,
    is_active       boolean      NOT NULL,
    vat_rate        numeric(5,2) NOT NULL CHECK (vat_rate >= 0 AND vat_rate <= 100),
    currency_symbol text         NOT NULL,
    time_zone       text         NOT NULL,
    valid_from      date         NOT NULL,
    valid_to        date,
    is_current      boolean      NOT NULL,

    CONSTRAINT dim_branch_natural_key UNIQUE (branch_id, valid_from),
    CONSTRAINT dim_branch_validity CHECK (valid_to IS NULL OR valid_to > valid_from),
    -- A current version is open-ended and a closed one has an end. Anything else is a bug in the
    -- SCD logic that would make T15's "exactly one current row" test meaningless.
    CONSTRAINT dim_branch_current_closed
        CHECK ((is_current AND valid_to IS NULL) OR (NOT is_current AND valid_to IS NOT NULL))
);

CREATE UNIQUE INDEX dim_branch_one_current
    ON dim_branch (branch_id) WHERE is_current;

COMMENT ON COLUMN dim_branch.vat_rate IS
    'A percentage, 12.00 means 12 per cent (rule S-20). Not a fraction: 0.12 would mean 0.12 per cent.';

-- =============================================================================================
-- dim_item                                                    (doc section 6.1, rules M-03, M-06)
--
-- SCD Type 2, and the one place where this model departs from Lab 2. The natural key is
-- `item_ref`, built from the product name, because `inventory_item_id` is null on 93.4% of sale
-- lines (finding F-01). The catalogue link is an attribute here, not the identity.
-- =============================================================================================
CREATE TABLE dim_item (
    item_key          bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_ref          text         NOT NULL,
    item_name         text         NOT NULL,
    inventory_item_id uuid,
    sku               text,
    category          text         NOT NULL,
    uom               text,
    unit_price        numeric(14,2),
    unit_cost         numeric(14,2),
    is_catalogue_item boolean      NOT NULL,
    valid_from        date         NOT NULL,
    valid_to          date,
    is_current        boolean      NOT NULL,

    CONSTRAINT dim_item_natural_key UNIQUE (item_ref, valid_from),
    CONSTRAINT dim_item_ref_basis CHECK (item_ref ~ '^(name|inventory):'),
    CONSTRAINT dim_item_validity CHECK (valid_to IS NULL OR valid_to > valid_from),
    CONSTRAINT dim_item_current_closed
        CHECK ((is_current AND valid_to IS NULL) OR (NOT is_current AND valid_to IS NOT NULL)),
    CONSTRAINT dim_item_money
        CHECK ((unit_price IS NULL OR unit_price >= 0) AND (unit_cost IS NULL OR unit_cost >= 0)),
    -- A product is a catalogue item exactly when it has a catalogue row behind it (rule C-02).
    CONSTRAINT dim_item_catalogue_link
        CHECK (is_catalogue_item = (inventory_item_id IS NOT NULL))
);

CREATE UNIQUE INDEX dim_item_one_current
    ON dim_item (item_ref) WHERE is_current;

COMMENT ON COLUMN dim_item.item_ref IS
    'Product identity: ''name:'' plus the normalised name printed on the sale line (rule S-12). '
    'The prefix says what the identity is based on, which matters when 93% of products have no id.';

COMMENT ON COLUMN dim_item.unit_cost IS
    'NULL means the cost is unknown and is never 0 (rule C-05). A zero would claim the goods were '
    'free and inflate every margin computed from it.';

-- =============================================================================================
-- dim_order_status                                            (doc section 6.1, rule M-04)
--
-- Static: seeded here, never derived from a batch. A seventh status at the source therefore fails
-- check T16 instead of quietly becoming a dimension row.
-- =============================================================================================
CREATE TABLE dim_order_status (
    status_key   smallint PRIMARY KEY,
    status_name  text     NOT NULL UNIQUE,
    status_order smallint NOT NULL,
    is_backlog   boolean  NOT NULL,
    is_terminal  boolean  NOT NULL,

    CONSTRAINT dim_order_status_position CHECK (status_order BETWEEN 1 AND 6),
    CONSTRAINT dim_order_status_kind CHECK (NOT (is_backlog AND is_terminal))
);

INSERT INTO dim_order_status (status_key, status_name, status_order, is_backlog, is_terminal)
VALUES
    (1, 'Pending',          1, true,  false),
    (2, 'Designing',        2, true,  false),
    (3, 'In Production',    3, true,  false),
    (4, 'Ready for Pickup', 4, true,  false),
    (5, 'Completed',        5, false, true),
    (6, 'Delivered',        6, false, true)
ON CONFLICT (status_key) DO NOTHING;

-- =============================================================================================
-- fct_daily_sales                                              (doc section 6.1, rules A-01, B-01…B-10)
--
-- One row per business_date x branch. The money columns are related by identity, and the CHECK
-- constraints below state those identities so a broken aggregate cannot be stored at all:
--
--   gross_revenue        = net_revenue + tax_total
--   net_revenue          = line_revenue_total - line_discount_total - unallocated_discount
--   unallocated_discount = discount_total - line_discount_total      (and never negative)
-- =============================================================================================
CREATE TABLE fct_daily_sales (
    business_date         date         NOT NULL REFERENCES dim_date (date_key),
    branch_key            bigint       NOT NULL REFERENCES dim_branch (branch_key),
    transaction_count     integer      NOT NULL CHECK (transaction_count >= 0),
    line_count            integer      NOT NULL CHECK (line_count >= 0),
    units_sold            integer      NOT NULL CHECK (units_sold >= 0),
    gross_revenue         numeric(14,2) NOT NULL CHECK (gross_revenue >= 0),
    net_revenue           numeric(14,2) NOT NULL CHECK (net_revenue >= 0),
    tax_total             numeric(14,2) NOT NULL CHECK (tax_total >= 0),
    line_revenue_total    numeric(14,2) NOT NULL CHECK (line_revenue_total >= 0),
    discount_total        numeric(14,2) NOT NULL CHECK (discount_total >= 0),
    line_discount_total   numeric(14,2) NOT NULL CHECK (line_discount_total >= 0),
    unallocated_discount  numeric(14,2) NOT NULL CHECK (unallocated_discount >= 0),
    cogs                  numeric(14,2) NOT NULL CHECK (cogs >= 0),
    revenue_costed        numeric(14,2) NOT NULL CHECK (revenue_costed >= 0),
    cogs_coverage_pct     numeric(6,2) NOT NULL CHECK (cogs_coverage_pct BETWEEN 0 AND 100),
    gross_profit          numeric(14,2),
    margin_pct            numeric(6,2),
    gross_profit_costed   numeric(14,2) NOT NULL,
    margin_pct_costed     numeric(6,2),
    avg_transaction_value numeric(14,2) CHECK (avg_transaction_value IS NULL OR avg_transaction_value >= 0),
    settled_total         numeric(14,2) NOT NULL CHECK (settled_total >= 0),
    cash_total            numeric(14,2) NOT NULL CHECK (cash_total >= 0),
    card_total            numeric(14,2) NOT NULL CHECK (card_total >= 0),
    custom_order_total    numeric(14,2) NOT NULL CHECK (custom_order_total >= 0),
    voided_count          integer      NOT NULL CHECK (voided_count >= 0),
    voided_amount         numeric(14,2) NOT NULL CHECK (voided_amount >= 0),

    PRIMARY KEY (business_date, branch_key),
    CONSTRAINT fct_daily_sales_tax_identity CHECK (gross_revenue = net_revenue + tax_total),
    CONSTRAINT fct_daily_sales_discount_identity
        CHECK (net_revenue = line_revenue_total - line_discount_total - unallocated_discount),
    CONSTRAINT fct_daily_sales_unallocated
        CHECK (unallocated_discount = discount_total - line_discount_total),
    CONSTRAINT fct_daily_sales_settlement CHECK (settled_total = cash_total + card_total + custom_order_total),
    -- Rule B-10: a whole-day profit exists only when every peso of revenue has a known cost.
    CONSTRAINT fct_daily_sales_profit_needs_coverage
        CHECK ((cogs_coverage_pct = 100) = (gross_profit IS NOT NULL))
);

COMMENT ON COLUMN fct_daily_sales.gross_profit IS
    'NULL unless cogs_coverage_pct = 100 (rule B-10). Read gross_profit_costed with '
    'cogs_coverage_pct for the costed slice; never read this as a whole-day figure.';

COMMENT ON COLUMN fct_daily_sales.line_revenue_total IS
    'Itemised revenue, before any discount. It is the denominator of cogs_coverage_pct and the '
    'reference side of the product reconciliation (check T12).';

-- =============================================================================================
-- fct_daily_product_demand                                     (doc section 6.1, rules A-02, B-04)
--
-- One row per business_date x branch x item that sold. Deliberately not densified: a zero row
-- would be indistinguishable from a day the batch never processed, and the unsold items a reorder
-- decision needs live in fct_daily_stock_snapshot.
-- =============================================================================================
CREATE TABLE fct_daily_product_demand (
    business_date       date         NOT NULL REFERENCES dim_date (date_key),
    branch_key          bigint       NOT NULL REFERENCES dim_branch (branch_key),
    item_key            bigint       NOT NULL REFERENCES dim_item (item_key),
    line_count          integer      NOT NULL CHECK (line_count >= 0),
    quantity_sold       integer      NOT NULL CHECK (quantity_sold >= 0),
    line_revenue        numeric(14,2) NOT NULL CHECK (line_revenue >= 0),
    discount_total      numeric(14,2) NOT NULL CHECK (discount_total >= 0),
    revenue             numeric(14,2) NOT NULL CHECK (revenue >= 0),
    cogs                numeric(14,2) NOT NULL CHECK (cogs >= 0),
    is_costed           boolean      NOT NULL,
    demand_window_days  smallint     NOT NULL CHECK (demand_window_days >= 1),
    avg_daily_demand    numeric(10,2) NOT NULL CHECK (avg_daily_demand >= 0),
    forecast_demand_30d numeric(10,2) NOT NULL CHECK (forecast_demand_30d >= 0),

    PRIMARY KEY (business_date, branch_key, item_key),
    CONSTRAINT fct_daily_product_demand_revenue CHECK (revenue = line_revenue - discount_total)
);

CREATE INDEX fct_daily_product_demand_item_idx
    ON fct_daily_product_demand (item_key);

COMMENT ON COLUMN fct_daily_product_demand.is_costed IS
    'True when dim_item.unit_cost is known for this product version. cogs is 0 when it is false, '
    'so a consumer computing a margin must read this flag first (rule B-04).';

-- =============================================================================================
-- fct_daily_stock_snapshot                                     (doc section 6.1, rules A-07, B-11…B-13)
--
-- One row per business_date x branch x catalogue item, for the TARGET date only. Stock is a
-- point-in-time measure: rebuilding a look-back date with tonight's catalogue would destroy the
-- record of what was on the shelf that day, which is why this is a separate fact from demand.
-- =============================================================================================
CREATE TABLE fct_daily_stock_snapshot (
    business_date       date     NOT NULL REFERENCES dim_date (date_key),
    branch_key          bigint   NOT NULL REFERENCES dim_branch (branch_key),
    item_key            bigint   NOT NULL REFERENCES dim_item (item_key),
    stock_on_hand       integer  NOT NULL CHECK (stock_on_hand >= 0),
    reorder_level       integer  NOT NULL CHECK (reorder_level >= 0),
    stock_status        text     NOT NULL,
    recommended_reorder integer  NOT NULL CHECK (recommended_reorder >= 0),

    PRIMARY KEY (business_date, branch_key, item_key),
    -- Rule B-11, stated once so the word and the numbers cannot disagree.
    CONSTRAINT fct_daily_stock_snapshot_status CHECK (
        (stock_status = 'critical' AND stock_on_hand = 0)
        OR (stock_status = 'warning' AND stock_on_hand > 0 AND stock_on_hand <= reorder_level)
        OR (stock_status = 'healthy' AND stock_on_hand > reorder_level)
    )
);

CREATE INDEX fct_daily_stock_snapshot_item_idx
    ON fct_daily_stock_snapshot (item_key);

COMMENT ON COLUMN fct_daily_stock_snapshot.stock_on_hand IS
    'Semi-additive: a snapshot per day, never summed across days (rule B-12).';

-- =============================================================================================
-- fct_daily_order_status                                       (doc section 6.1, rules A-03, A-05)
--
-- One row per business_date x branch x status, densified across all six statuses for any
-- (date, branch) that has at least one order: a funnel with a missing step reads as a broken
-- funnel. The cohort is orders RAISED that day (rule X-04), not orders touched that day.
-- =============================================================================================
CREATE TABLE fct_daily_order_status (
    business_date      date         NOT NULL REFERENCES dim_date (date_key),
    branch_key         bigint       NOT NULL REFERENCES dim_branch (branch_key),
    status_key         smallint     NOT NULL REFERENCES dim_order_status (status_key),
    order_count        integer      NOT NULL CHECK (order_count >= 0),
    order_value        numeric(14,2) NOT NULL CHECK (order_value >= 0),
    custom_order_count integer      NOT NULL CHECK (custom_order_count >= 0),
    avg_order_value    numeric(14,2) CHECK (avg_order_value IS NULL OR avg_order_value >= 0),

    PRIMARY KEY (business_date, branch_key, status_key),
    CONSTRAINT fct_daily_order_status_custom CHECK (custom_order_count <= order_count)
);

-- =============================================================================================
-- quarantine_rows                                              (doc sections 3, 7 and 9)
--
-- Records that could not be safely transformed, with the rule that caught them and the batch they
-- belong to. Nothing is ever dropped silently: a record is retained or it is here.
-- =============================================================================================
CREATE TABLE quarantine_rows (
    quarantine_id  bigserial   PRIMARY KEY,
    batch_id       text        NOT NULL,
    run_id         uuid        NOT NULL,
    parent_run_id  uuid        NOT NULL,
    business_date  date        NOT NULL,
    source_table   text        NOT NULL,
    source_id      text        NOT NULL,
    rule_id        text        NOT NULL,
    reason         text        NOT NULL,
    detail         text,
    payload        jsonb       NOT NULL DEFAULT '{}'::jsonb,
    quarantined_at timestamptz NOT NULL DEFAULT now(),

    -- A rerun must not quarantine the same row twice (doc section 1.2).
    CONSTRAINT quarantine_rows_once UNIQUE (batch_id, source_table, source_id, rule_id)
);

CREATE INDEX quarantine_rows_batch_idx ON quarantine_rows (batch_id);
CREATE INDEX quarantine_rows_date_idx  ON quarantine_rows (business_date);

COMMENT ON COLUMN quarantine_rows.source_id IS
    'Text, not uuid: six source tables key on a uuid and business_settings keys on an integer. '
    'The offending row itself is in payload.';
COMMENT ON COLUMN quarantine_rows.payload IS
    'The offending row as this stage sees it. No customer data is stored here, because Stage 1 '
    'does not extract any (doc section 9).';

-- =============================================================================================
-- transformation_runs                                          (doc sections 6.1 and 8)
--
-- One row per output table per batch, plus one run-level row whose table_name is null. The same
-- grain as pipeline_runs, so the two stages' ledgers read alike.
-- =============================================================================================
CREATE TABLE transformation_runs (
    run_id                          uuid        NOT NULL,
    batch_id                        text        NOT NULL,
    parent_run_id                   uuid        NOT NULL,
    pipeline_name                   text        NOT NULL,
    business_date                   date        NOT NULL,
    batch_window_start              date        NOT NULL,
    batch_window_end                date        NOT NULL,
    table_name                      text,
    transformation_started_at       timestamptz NOT NULL,
    transformation_ended_at         timestamptz,
    transformation_duration_seconds integer     CHECK (transformation_duration_seconds >= 0),
    transformation_status           text        NOT NULL,
    records_read                    integer     NOT NULL DEFAULT 0 CHECK (records_read >= 0),
    records_output                  integer     NOT NULL DEFAULT 0 CHECK (records_output >= 0),
    records_rejected                integer     NOT NULL DEFAULT 0 CHECK (records_rejected >= 0),
    records_modified                integer     NOT NULL DEFAULT 0 CHECK (records_modified >= 0),
    validation_results              jsonb,
    decision                        text,
    error_code                      text,
    error_message                   text,
    code_version                    text        NOT NULL,

    CONSTRAINT transformation_runs_status
        CHECK (transformation_status IN ('running', 'success', 'failed', 'skipped')),
    CONSTRAINT transformation_runs_decision CHECK (
        decision IS NULL
        OR decision IN ('APPROVED', 'APPROVED WITH WARNING', 'MANUAL REVIEW', 'REJECTED', 'SKIPPED')
    ),
    CONSTRAINT transformation_runs_window CHECK (batch_window_end >= batch_window_start)
);

-- One row per table per batch. COALESCE stands in for the run-level row, whose table_name is null
-- and would otherwise be exempt from a unique index (nulls never conflict).
CREATE UNIQUE INDEX transformation_runs_batch_table_key
    ON transformation_runs (batch_id, COALESCE(table_name, '__run__'));

CREATE INDEX transformation_runs_date_idx   ON transformation_runs (business_date);
CREATE INDEX transformation_runs_parent_idx ON transformation_runs (parent_run_id);

COMMENT ON COLUMN transformation_runs.parent_run_id IS
    'The extraction run this batch transformed. A logical reference only: pipeline_runs has no '
    'single-column key (its natural key is (run_id, COALESCE(table_name, ''__run__''))), so no '
    'foreign key can be declared against it.';

-- =============================================================================================
-- transformation_rule_counts                                   (doc sections 6.1 and 8)
--
-- "rules_applied" as rows rather than a jsonb blob: a blob cannot be indexed, summed, or charted,
-- and the whole point of the column is to answer "how many records did rule C-02 change?".
-- These counts are records MODIFIED and retained. They are not part of the reconciliation.
-- =============================================================================================
CREATE TABLE transformation_rule_counts (
    batch_id         text    NOT NULL,
    table_name       text    NOT NULL,
    rule_id          text    NOT NULL,
    business_date    date    NOT NULL,
    records_affected integer NOT NULL CHECK (records_affected >= 0),

    PRIMARY KEY (batch_id, table_name, rule_id)
);

COMMIT;
